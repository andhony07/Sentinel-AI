"""Pydantic models for SentinelAI structured AI diagnostic assistant.

Defines strongly-typed, schema-validated contracts for incident summaries,
evidence-grounded probable causes, investigation steps, safety-rated remediation
recommendations, and explicit uncertainty assessments.
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Optional

from pydantic import BaseModel, ConfigDict, Field


class ConfidenceLevel(str, Enum):
    """Confidence level of an evidence-backed hypothesis."""

    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"


class SafetyLevel(str, Enum):
    """Operational safety level of a remediation action."""

    SAFE = "SAFE"
    CAUTION = "CAUTION"
    CRITICAL = "CRITICAL"


class ProbableCause(BaseModel):
    """Root-cause hypothesis backed by observed telemetry evidence.

    Attributes:
        rank: Priority ranking (1 being most likely).
        hypothesis: Concise explanation of the suspected failure mechanism.
        confidence: Evaluated confidence level based on supporting evidence.
        supporting_evidence: Concrete empirical metrics or flags supporting this hypothesis.
    """

    model_config = ConfigDict(extra="ignore")

    rank: int = Field(ge=1, le=10, default=1, description="Priority ranking")
    hypothesis: str = Field(min_length=3, max_length=500, description="Root cause hypothesis")
    confidence: ConfidenceLevel = Field(
        default=ConfidenceLevel.MEDIUM, description="Confidence level"
    )
    supporting_evidence: list[str] = Field(
        default_factory=list,
        max_length=15,
        description="Empirical observations supporting the hypothesis",
    )


class RemediationAction(BaseModel):
    """Operational remediation step with explicit safety classification.

    Attributes:
        step_number: Ordered execution sequence index.
        action: Clear, actionable operational task for the human operator.
        command: Optional shell or diagnostic command suggestion.
        safety_level: Operational risk classification (SAFE, CAUTION, CRITICAL).
        precautions: Safety warnings, prerequisite checks, or potential side-effects.
    """

    model_config = ConfigDict(extra="ignore")

    step_number: int = Field(ge=1, le=20, default=1, description="Execution step order")
    action: str = Field(min_length=3, max_length=500, description="Recommended remediation action")
    command: Optional[str] = Field(
        default=None, max_length=500, description="Suggested non-destructive command"
    )
    safety_level: SafetyLevel = Field(
        default=SafetyLevel.SAFE, description="Safety classification"
    )
    precautions: str = Field(
        min_length=1, max_length=1000, description="Precautions and operator guidance"
    )


class InvestigationStep(BaseModel):
    """Specific telemetry probe or verification step to narrow down root cause."""

    model_config = ConfigDict(extra="ignore")

    step_number: int = Field(ge=1, le=20, default=1)
    description: str = Field(min_length=3, max_length=500)
    command: Optional[str] = Field(default=None, max_length=500)
    target_subsystem: Optional[str] = None


class AIIncidentDiagnosis(BaseModel):
    """Standardized consolidated incident diagnosis generated by SentinelAI.

    Attributes:
        incident_id: Unique diagnostic report identifier.
        timestamp: Time of diagnosis generation (UTC).
        status: High-level system state (e.g. NOMINAL, ANOMALY_DETECTED, HEURISTIC_EVALUATION).
        risk_category: Authoritative ML risk classification.
        health_score: Authoritative composite health score in [0.0, 100.0].
        anomaly_score: Authoritative normalized anomaly probability in [0.0, 1.0].
        incident_summary: Executive natural-language summary of system health or incident.
        probable_causes: Ranked list of root-cause hypotheses linked to evidence.
        investigation_steps: Prioritized sequence of diagnostic inspection steps.
        remediation_actions: Actionable remediation runbook with safety precautions.
        uncertainty_assessment: Explicit statement of evidence limits and unobserved domains.
        is_fallback: True if generated by deterministic heuristic fallback rather than LLM.
        model_used: Name of the active LLM or fallback engine.
        latency_ms: Time taken to evaluate the diagnosis in milliseconds.
        metadata: Optional auxiliary diagnostics metadata.
    """

    model_config = ConfigDict(extra="ignore")

    incident_id: str = Field(
        default_factory=lambda: f"diag_{uuid.uuid4().hex[:10]}",
        description="Unique report identifier",
    )
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Report timestamp (UTC)",
    )
    status: str = Field(
        default="EVALUATED", description="Operational status evaluation"
    )
    risk_category: str = Field(
        description="Authoritative operational risk tier (Normal, Low, Moderate, High, Critical)"
    )
    health_score: Optional[float] = Field(
        default=None, ge=0.0, le=100.0, description="Authoritative composite health score"
    )
    anomaly_score: float = Field(
        ge=0.0, le=1.0, description="Authoritative anomaly probability"
    )
    incident_summary: str = Field(
        min_length=5, max_length=2000, description="Executive incident summary"
    )
    probable_causes: list[ProbableCause] = Field(
        default_factory=list, max_length=10, description="Ranked probable causes"
    )
    investigation_steps: list[str] = Field(
        default_factory=list, max_length=15, description="Investigation steps"
    )
    remediation_actions: list[RemediationAction] = Field(
        default_factory=list, max_length=15, description="Actionable remediation runbook"
    )
    uncertainty_assessment: str = Field(
        min_length=1,
        max_length=2000,
        description="Explicit assessment of data limits and uncertainty",
    )
    is_fallback: bool = Field(
        default=False, description="True if generated by deterministic heuristic fallback"
    )
    model_used: str = Field(
        default="deterministic_rules", description="Model or engine identifier"
    )
    latency_ms: float = Field(
        ge=0.0, default=0.0, description="Inference evaluation latency in ms"
    )
    fallback_reason: Optional[str] = Field(
        default=None, description="Explanation why fallback was engaged if is_fallback is True"
    )
    metadata: dict[str, Any] = Field(
        default_factory=dict, description="Auxiliary runtime metadata"
    )

    def to_dict(self) -> dict[str, Any]:
        """Convert diagnosis instance to JSON-serializable dictionary."""
        return {
            "incident_id": self.incident_id,
            "timestamp": self.timestamp.isoformat(),
            "status": self.status,
            "risk_category": self.risk_category,
            "health_score": round(self.health_score, 1) if self.health_score is not None else None,
            "anomaly_score": round(self.anomaly_score, 4),
            "incident_summary": self.incident_summary,
            "probable_causes": [c.model_dump() for c in self.probable_causes],
            "investigation_steps": list(self.investigation_steps),
            "remediation_actions": [a.model_dump() for a in self.remediation_actions],
            "uncertainty_assessment": self.uncertainty_assessment,
            "is_fallback": self.is_fallback,
            "model_used": self.model_used,
            "latency_ms": round(self.latency_ms, 2),
            "fallback_reason": self.fallback_reason,
            "metadata": dict(self.metadata),
        }


class AIDiagnosisRequest(BaseModel):
    """Request payload for on-demand AI diagnosis evaluation."""

    scenario: Optional[str] = Field(
        default=None, description="Optional simulation scenario to evaluate"
    )
    persist: bool = Field(
        default=False, description="Whether to persist simulated samples to SQLite"
    )
    force_fallback: bool = Field(
        default=False, description="Force deterministic rule-based evaluation without LLM"
    )
